/**
 * Pure rendering of one architect projection and the dependency facts of its
 * revision into the exact files of docs/architecture/architect-view.spec.md.
 * It reads no compiler, filesystem or session state: the same input always
 * gives the same bytes, with no timestamp, host path or process value. Every
 * text field and list of a record is bounded here or by the projection's
 * limits, so a record's length does not grow with the project.
 */

const bounds = { purposeBytes: 600, consumers: 12, names: 4, headline: 8, exercises: 12 } as const;

