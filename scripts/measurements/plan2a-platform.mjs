#!/usr/bin/env node
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { chmod, mkdir, mkdtemp, readFile, readdir, realpath, rm, symlink, writeFile } from 'node:fs/promises';
import { arch, platform, release } from 'node:os';
import { dirname, join, relative, resolve } from 'node:path';
import { installedCommand, packageRoot } from './common.mjs';
import { runCommand } from './plan2a-fixtures.mjs';
import { writeMaterializeFixture, materializeFixtureFiles } from '../reference-harness/plan2a-materialize-fixture.ts';

/**
 * Plan 2A (`I2A-12:linux-macos-bytes`) platform evidence: the same
 * checked-in, real, small filesystem/process fixture
 * (`scripts/reference-harness/plan2a-materialize-fixture.ts`, already used by
 * the I2A-09/10 reference-harness cases) materialized through the real
 * installed CLI and production daemon, producing a relative-tree/bytes
 * manifest (one sha256 per relative path) plus real symlink, rollback and
 * no-op process outcomes. This host is Linux only: run this script unchanged
 * on a macOS host to produce the missing half.
 *
 * Usage: node scripts/measurements/plan2a-platform.mjs [--output FILE]
 */
const args = process.argv.slice(2);
const outputArgIndex = args.indexOf('--output');
const output = resolve(outputArgIndex === -1 ? join(packageRoot, 'scripts/measurements/results', `plan2a-platform-${platform()}.json`)
  : args[outputArgIndex + 1]);
assert.ok(['linux', 'darwin'].includes(platform()), 'Linux or macOS required');

async function manifestOf(root) {
  const entries = [];
  async function walk(current, prefix) {
    for (const item of await readdir(current, { withFileTypes: true })) {
      const rel = prefix ? `${prefix}/${item.name}` : item.name;
      const path = join(current, item.name);
      if (item.isSymbolicLink()) continue;
      if (item.isDirectory()) { if (item.name === 'node_modules') continue; await walk(path, rel); }
      else if (rel.split('/').includes('.ramify')) {
        const bytes = await readFile(path);
        entries.push({ path: rel, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') });
      }
    }
  }
  await walk(root, '');
  return entries.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
}

async function withOwnedDaemon(run) {
  const owned = await realpath(await mkdtemp(join('/tmp', 'rm2a-plat-')));
  const endpoint = join(owned, 'endpoint');
  await mkdir(endpoint, { mode: 0o700 });
  const env = { RAMIFY_ENDPOINT_DIR: endpoint };
  const install = await runCommand('npm', ['install', '--prefix', join(owned, 'install'), '--offline', '--ignore-scripts', '--no-audit', '--no-fund', packageRoot], { timeoutMs: 60000 });
  assert.equal(install.code, 0, install.stderr);
  const { executable } = installedCommand(join(owned, 'install'));
  try { return await run(executable, env); }
  finally {
    await runCommand(executable, ['daemon', 'stop', '--format', 'json'], { env, timeoutMs: 10000 }).catch(() => {});
    await rm(owned, { recursive: true, force: true });
  }
}

const report = {
  schemaVersion: 'ramify.plan2a-platform/1', phase: 'plan2a-platform', measuredAt: new Date().toISOString(),
  evidenceKind: 'platform',
  fixture: { source: 'scripts/reference-harness/plan2a-materialize-fixture.ts', files: Object.keys(materializeFixtureFiles).sort() },
  environment: { node: process.version, platform: platform(), release: release(), arch: arch() },
  cases: {}, manifest: [], passed: false, failures: [],
};

try {
  // 1. First publication + relative-tree/bytes manifest, and the real
  // unchanged-repeat no-op.
  const manifestRoot = await mkdtemp(join(packageRoot, '.reference-work', 'plan2a-platform-manifest-'));
  await writeMaterializeFixture(manifestRoot);
  await withOwnedDaemon(async (executable, env) => {
    const first = await runCommand(executable, ['materialize', '--all'], { cwd: manifestRoot, env, timeoutMs: 60000 });
    report.cases.firstPublication = { code: first.code, stdout: first.stdout };
    assert.equal(first.code, 0, first.stderr);
    report.manifest = await manifestOf(manifestRoot);
    const repeat = await runCommand(executable, ['materialize', '--all'], { cwd: manifestRoot, env, timeoutMs: 60000 });
    report.cases.noOpRepeat = { code: repeat.code, stdout: repeat.stdout,
      zeroBytesWritten: /0 bytes written/.test(repeat.stdout) };
    assert.equal(repeat.code, 0, repeat.stderr);
    assert.ok(report.cases.noOpRepeat.zeroBytesWritten, 'Repeat materialization must write zero bytes');
    const repeatManifest = await manifestOf(manifestRoot);
    report.cases.noOpRepeat.manifestUnchanged = JSON.stringify(repeatManifest) === JSON.stringify(report.manifest);
    assert.ok(report.cases.noOpRepeat.manifestUnchanged, 'A no-op repeat must not change any generated byte');
  });
  await rm(manifestRoot, { recursive: true, force: true });

  // 2. Symlink refusal: a symlink occupying the final `.ramify` target itself,
  // in a fresh fixture copy, must refuse publication without following or
  // deleting it (the same real production path I2A-07:symlink-traversal
  // proves at the publisher API layer, exercised here end to end through the
  // real CLI and daemon on this platform).
  const symlinkRoot = await mkdtemp(join(packageRoot, '.reference-work', 'plan2a-platform-symlink-'));
  await writeMaterializeFixture(symlinkRoot);
  const elsewhere = join(symlinkRoot, 'subs/app/elsewhere');
  await mkdir(elsewhere);
  await symlink(elsewhere, join(symlinkRoot, 'subs/app/src/.ramify'));
  await withOwnedDaemon(async (executable, env) => {
    const outcome = await runCommand(executable, ['materialize', '--all'], { cwd: symlinkRoot, env, timeoutMs: 60000 });
    report.cases.symlinkRefusal = { code: outcome.code, stdout: outcome.stdout };
    assert.equal(outcome.code, 2, 'A symlinked target must refuse publication (exit 2), never publish through it');
    assert.ok(!outcome.stdout.includes('Materialized: revision'), 'A refused publication must not claim success');
  });
  const stillSymlink = await readdir(join(symlinkRoot, 'subs/app/src'), { withFileTypes: true })
    .then(entries => entries.find(entry => entry.name === '.ramify')?.isSymbolicLink());
  report.cases.symlinkRefusal.symlinkUntouched = stillSymlink === true;
  assert.ok(report.cases.symlinkRefusal.symlinkUntouched, 'The symlink itself must survive, neither followed nor deleted');
  await rm(symlinkRoot, { recursive: true, force: true });

  // 3. Rollback: a real filesystem permission fault forces a mid-switch
  // publish failure on a second, changed materialization; the earlier,
  // already-published target must be restored byte-for-byte, and the
  // outcome must never claim success. `chmod` is POSIX and identical on
  // Linux and macOS, unlike a Node-level fault injection point.
  const rollbackRoot = await mkdtemp(join(packageRoot, '.reference-work', 'plan2a-platform-rollback-'));
  await writeMaterializeFixture(rollbackRoot);
  await withOwnedDaemon(async (executable, env) => {
    const first = await runCommand(executable, ['materialize', '--all'], { cwd: rollbackRoot, env, timeoutMs: 60000 });
    assert.equal(first.code, 0, first.stderr);
    const before = await manifestOf(rollbackRoot);
    // A real source edit changes what the next materialize would publish.
    const libApi = join(rollbackRoot, 'subs/lib/src/api.ts');
    await writeFile(libApi, (await readFile(libApi, 'utf8')) + "\nexport function widgetTwo(): string { return 'w2'; }\n");
    await writeFile(join(rollbackRoot, 'subs/lib/module.ramify'),
      (await readFile(join(rollbackRoot, 'subs/lib/module.ramify'), 'utf8')) + 'expose-src widgetTwo from "api.ts" to parent\n');
    // Relay the new export all the way to `app` too (not just lib's
    // automatic parent visibility at the root), so `app`'s own already-
    // published ordinary target is genuinely part of this second
    // materialization's changed set, not just the root's.
    await writeFile(join(rollbackRoot, 'module.ramify'),
      (await readFile(join(rollbackRoot, 'module.ramify'), 'utf8')).replace('expose-sub widget from lib to descendants', 'expose-sub widget, widgetTwo from lib to descendants'));
    // Deny write access to one already-published target's parent directory,
    // so its own switch (a rename into that directory) fails after at least
    // one sibling target has already switched.
    const deniedParent = join(rollbackRoot, 'subs/app/src');
    await chmod(deniedParent, 0o500);
    let outcome;
    try { outcome = await runCommand(executable, ['materialize', '--all'], { cwd: rollbackRoot, env, timeoutMs: 60000 }); }
    finally { await chmod(deniedParent, 0o755); }
    report.cases.rollback = { code: outcome.code, stdout: outcome.stdout };
    assert.notEqual(outcome.code, 0, 'A publication that cannot complete every target must never report success');
    assert.ok(!outcome.stdout.includes('bytes written') || outcome.code !== 0, 'A failed publication must not claim a written outcome');
    const after = await manifestOf(rollbackRoot);
    report.cases.rollback.oldBytesPreserved = JSON.stringify(after) === JSON.stringify(before);
    assert.ok(report.cases.rollback.oldBytesPreserved, 'Every earlier target must be restored byte-for-byte after a failed publication');
  });
  await rm(rollbackRoot, { recursive: true, force: true });

  report.passed = true;
} catch (error) {
  report.failures.push(error.stack ?? String(error));
  report.passed = false;
} finally {
  report.completedAt = new Date().toISOString();
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, JSON.stringify(report, null, 2) + '\n');
  process.stdout.write(JSON.stringify({ output, passed: report.passed, cases: Object.keys(report.cases),
    manifestEntries: report.manifest.length, failures: report.failures }, null, 2) + '\n');
  process.exitCode = report.passed ? 0 : 1;
}
