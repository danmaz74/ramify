import { performance } from 'node:perf_hooks';
import { readFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { resolve, dirname, relative } from 'node:path';
import { API } from '../../../node_modules/typescript/dist/api/sync/api.js';
import { buildCatalog } from '../../../dist/subs/analysis/subs/typescript/src/catalog.js';
import { collectAccesses } from '../../../dist/subs/analysis/subs/typescript/src/accesses.js';

const report = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const root = report.scope.root;
const configuration = resolve(root, report.scope.configuration);
const inventory = report.snapshot.inventory;
const areas = report.snapshot.areas;
const limits = { maxExports: 250000, maxAccesses: 250000, maxSelections: 1000000, maxForwardingDepth: 256, deadlineMs: 90000 };
const inputs = { inventory, areas, limits };
const marks = [];
let last = performance.now();
const mark = (label) => { const now = performance.now(); marks.push([label, (now - last).toFixed(1)]); last = now; };

// Replicate the helper's synthetic config and resource witness as virtual files.
const synthetic = resolve(dirname(configuration), '.ramify-probe-inputs.json');
const witness = resolve(dirname(configuration), '.ramify-probe-inputs.ts');
const virtual = new Map();
const override = new Map();
const readFile = p => { p = resolve(p); return virtual.get(p) ?? override.get(p); };
const fileExists = p => virtual.has(resolve(p)) ? true : undefined;
const realpath = p => virtual.has(resolve(p)) ? resolve(p) : undefined;
const api = new API({ cwd: root, fs: { readFile, fileExists, realpath } });
const parsed = api.parseConfigFile(configuration);
const roots = new Set(parsed.fileNames);
for (const f of inventory.files) if (f.kind === 'source') roots.add(resolve(root, f.path));
roots.add(witness);
virtual.set(synthetic, JSON.stringify({ extends: configuration, files: [...roots].sort(), include: [], exclude: [] }));
const imports = inventory.files.filter(f => f.kind === 'resource').map((f, i) => { let s = relative(dirname(witness), resolve(root, f.path)); if (!s.startsWith('.')) s = './' + s; return `import * as r${i} from ${JSON.stringify(s)};\n`; });
virtual.set(witness, imports.join('') + 'export {};\n');
mark('api + parseConfigFile');
let snapshot = api.updateSnapshot({ openProjects: [synthetic] });
let project = snapshot.getProject(synthetic);
mark(`initial snapshot (${project.program.getSourceFileNames().length} program files)`);
const host = { fileExists: p => virtual.has(resolve(p)) || existsSync(p), readFile: p => { const v = readFile(p); if (v !== undefined) return v; try { return readFileSync(p, 'utf8'); } catch { return null; } }, resourceWitness: witness };
let runtime = new Map();
let catalog = buildCatalog(project, inputs, host, runtime);
mark(`REAL buildCatalog, cold checker (${catalog.originals.length} originals, ${catalog.files.length} files)`);
let accesses = collectAccesses(project, inputs, host, catalog, runtime);
mark(`REAL collectAccesses, warm checker (${accesses.accesses.length} accesses)`);
const rss = () => { try { return execSync(`ps -o rss= --ppid ${process.pid}`).toString().trim().split('\n').map(Number).reduce((a, b) => a + b, 0) / 1024; } catch { return NaN; } };
console.log('tsgo server RSS MiB (children of this process):', rss().toFixed(1), '| this process RSS MiB:', (process.memoryUsage().rss / 1048576).toFixed(1));

// Edit one owned source file (append an export) and redo the conservative path on the warm server.
const owned = inventory.files.filter(f => f.kind === 'source').map(f => resolve(root, f.path));
const target = owned[Math.floor(owned.length / 2)];
override.set(target, readFileSync(target, 'utf8') + '\nexport const ramifyProbeAdded = 1;\n');
last = performance.now();
const prev = snapshot;
snapshot = api.updateSnapshot({ fileChanges: { changed: [target] } });
project = snapshot.getProject(synthetic);
mark(`updateSnapshot after edit of ${relative(root, target)}`);
runtime = new Map();
catalog = buildCatalog(project, inputs, host, runtime);
mark(`REAL buildCatalog, full, warm server (${catalog.originals.length} originals)`);
accesses = collectAccesses(project, inputs, host, catalog, runtime);
mark(`REAL collectAccesses, full, warm server (${accesses.accesses.length} accesses)`);
prev.dispose();
// Same again (steady state)
override.delete(target);
const prev2 = snapshot;
snapshot = api.updateSnapshot({ fileChanges: { changed: [target] } });
project = snapshot.getProject(synthetic);
mark('updateSnapshot after revert');
runtime = new Map();
catalog = buildCatalog(project, inputs, host, runtime);
mark('REAL buildCatalog, full, warm server');
accesses = collectAccesses(project, inputs, host, catalog, runtime);
mark('REAL collectAccesses, full, warm server');
prev2.dispose();
console.log('after edits: tsgo RSS MiB', rss().toFixed(1), '| this process RSS MiB:', (process.memoryUsage().rss / 1048576).toFixed(1));
snapshot.dispose(); api.close();
console.log(root);
for (const [label, ms] of marks) console.log(ms.padStart(8), 'ms ', label);
